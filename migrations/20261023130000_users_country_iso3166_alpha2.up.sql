UPDATE users u
SET country = UPPER(COALESCE(
    (SELECT n.code FROM norm n
      WHERE n.match = lower(btrim(u.country))
      ORDER BY n.code
      LIMIT 1),
    ''));

ALTER TABLE users
    ADD CONSTRAINT users_country_iso3166_alpha2
    CHECK (country = '' OR country ~ '^[A-Z]{2}$');
