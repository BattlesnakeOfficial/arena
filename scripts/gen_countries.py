#!/usr/bin/env python3
"""Generate server/src/countries/data.rs and /tmp/norm_values.sql for DEV-1897.

Input: all.csv from
  https://raw.githubusercontent.com/lukes/ISO-3166-Countries-with-Regional-Codes/master/all/all.csv

Outputs (constants below):
  OUTPUT_RS  — GENERATED DATA ONLY (Country, COUNTRIES, CSV_NAMES, ALIASES).
               The hand-written API (normalize/is_valid_code/name_for) and the
               unit tests live in server/src/countries.rs, which this script
               NEVER touches — regenerating is always safe.
  OUTPUT_SQL — the `WITH norm(match, code) AS (VALUES ...)` body for the
               migration (transient; pasted once into the .up.sql file).

Run from the repo root: python3 scripts/gen_countries.py /tmp/all.csv
"""
import csv
import sys

OUTPUT_RS = "server/src/countries/data.rs"
OUTPUT_SQL = "/tmp/norm_values.sql"

# Friendlier display names for countries whose UN-style names are awkward.
# These replace the CSV name in the UI AND participate in normalize() matching.
DISPLAY_OVERRIDES = {
    "GB": "United Kingdom", "US": "United States", "RU": "Russia",
    "KR": "South Korea", "KP": "North Korea", "VN": "Vietnam", "LA": "Laos",
    "BN": "Brunei", "SY": "Syria", "IR": "Iran", "MD": "Moldova",
    "TZ": "Tanzania", "BO": "Bolivia", "VE": "Venezuela", "TW": "Taiwan",
    "FM": "Micronesia", "PS": "Palestine", "VA": "Vatican City",
    "NL": "Netherlands", "CD": "DR Congo", "CG": "Congo",
    "VG": "British Virgin Islands", "VI": "U.S. Virgin Islands",
    "SH": "Saint Helena", "BQ": "Caribbean Netherlands",
    "CC": "Cocos Islands", "FK": "Falkland Islands", "MF": "Saint Martin",
    "SX": "Sint Maarten", "TR": "Turkey",
}

# Extra lowercase aliases -> code, on top of code/CSV-name/display-name
# matching. (Lowercase spellings of the codes themselves need no alias —
# code matching is case-insensitive.)
ALIASES = {
    "usa": "US", "america": "US",
    "uk": "GB", "great britain": "GB", "britain": "GB", "england": "GB",
    "scotland": "GB", "wales": "GB", "northern ireland": "GB",
    "holland": "NL", "czech republic": "CZ",
    "ivory coast": "CI", "cape verde": "CV",
    "burma": "MM", "swaziland": "SZ", "macedonia": "MK", "turkiye": "TR",
    "uae": "AE", "vatican": "VA", "east timor": "TL",
    "congo-brazzaville": "CG", "republic of the congo": "CG",
    "democratic republic of congo": "CD", "drc": "CD",
}

def main() -> None:
    rows = []
    with open(sys.argv[1] if len(sys.argv) > 1 else "all.csv",
              newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            code = row["alpha-2"].upper()
            assert len(code) == 2 and code.isalpha()
            display = DISPLAY_OVERRIDES.get(code, row["name"])
            rows.append((code, row["name"].strip(), display))
    assert len(rows) == 249, f"expected 249 rows, got {len(rows)}"

    rs = sorted(rows, key=lambda r: (r[2].lower(), r[0]))
    out = [
        "// GENERATED by scripts/gen_countries.py (DEV-1897). Do not edit by",
        "// hand; regenerate instead. Source: ISO-3166-1 alpha-2 officially",
        "// assigned codes (lukes/ISO-3166-Countries-with-Regional-Codes",
        "// all.csv) with display-name overrides and extra aliases. The",
        "// hand-written API and tests live in ../countries.rs.",
        "",
        "/// One ISO-3166-1 alpha-2 country. `code` is the stored value in",
        "/// `users.country`; `name` is the display name.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct Country {",
        "    pub code: &'static str,",
        "    pub name: &'static str,",
        "}",
        "",
        "/// All 249 officially assigned ISO-3166-1 alpha-2 countries, sorted",
        "/// by display name (the order the country `<select>` renders).",
        "pub const COUNTRIES: &[Country] = &[",
    ]
    for code, _csv_name, display in rs:
        out.append(f'    Country {{ code: "{code}", name: "{display}" }},')
    out += [
        "];",
        "",
        "/// (lowercase ISO CSV name, code) pairs, sorted by name. Keeps",
        "/// [`super::normalize`] in parity with the migration's VALUES list",
        "/// for UN-style names that differ from the display names.",
        "pub const CSV_NAMES: &[(&str, &str)] = &[",
    ]
    for name, code in sorted((n.lower(), c) for c, n, _d in rows):
        out.append(f'    ("{name}", "{code}"),')
    out += [
        "];",
        "",
        "/// Lowercase aliases accepted by [`super::normalize`] beyond",
        "/// code/CSV-name/display-name matches.",
        "pub const ALIASES: &[(&str, &str)] = &[",
    ]
    for alias, code in sorted(ALIASES.items()):
        out.append(f'    ("{alias}", "{code}"),')
    out.append("];")
    open(OUTPUT_RS, "w", encoding="utf-8").write("\n".join(out) + "\n")

    pairs: dict[str, str] = {}
    for code, csv_name, display in rows:
        pairs[code.lower()] = code
        pairs[csv_name.lower()] = code
        pairs[display.lower()] = code
    for alias, code in ALIASES.items():
        assert pairs.get(alias, code) == code, f"alias collision: {alias}"
        pairs[alias] = code
    keys = sorted(pairs)
    lines = [f"    ('{k.replace(chr(39), chr(39) * 2)}','{pairs[k]}')" for k in keys]
    open(OUTPUT_SQL, "w", encoding="utf-8").write(
        "WITH norm(match, code) AS (VALUES\n" + ",\n".join(lines) + ")\n")
    print(f"rows={len(rows)} match-keys={len(keys)} aliases={len(ALIASES)}")

if __name__ == "__main__":
    main()
